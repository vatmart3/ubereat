// Visite visuelle des écrans (dev) : node scripts/dev/tour.mjs <base> <outDir> <light|dark>
import { chromium } from "@playwright/test";
const [,, base, out, scheme = "light"] = process.argv;
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, colorScheme: scheme, hasTouch: true });
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("pageerror:", e.message));
page.on("console", (m) => m.type() === "error" && console.log("console:", m.text()));
const shot = async (name, full = true) => { await page.screenshot({ path: `${out}/${name}-${scheme}.png`, fullPage: full }); console.log("shot", name); };

await page.goto(base + "/app/nouvelle");
await page.getByTestId("platform-deliveroo").click();
await page.keyboard.type("DR-2207");
await page.getByTestId("amount").fill("31,40");
await page.keyboard.press("Enter");
await page.getByTestId("input-sac").setInputFiles("supabase/seed-assets/sac-b.jpg");
await page.getByTestId("input-ticket").setInputFiles("supabase/seed-assets/ticket.jpg");
await page.waitForTimeout(900);
await shot("w2-photos", false);
await page.getByTestId("next-step").click();
await page.getByTestId("recent-courier").nth(1).click();
await shot("w3-courier", false);
await page.getByTestId("next-step").click();
const pad = await page.getByTestId("signature-pad").boundingBox();
await page.mouse.move(pad.x + 30, pad.y + 100); await page.mouse.down();
for (let i = 0; i < 30; i++) await page.mouse.move(pad.x + 30 + i * 9, pad.y + 90 + Math.sin(i / 2) * 30);
await page.mouse.up();
await page.getByTestId("confirm-closed").click();
await shot("w4-seal", true);
const hold = await page.getByTestId("hold-to-seal").boundingBox();
await page.mouse.move(hold.x + 50, hold.y + 30); await page.mouse.down(); await page.waitForTimeout(450);
await shot("w4-holding", false);
await page.waitForTimeout(700); await page.mouse.up();
await page.getByTestId("confirmation").waitFor();
await page.waitForTimeout(800);
await shot("w5-printing", false);
await page.waitForTimeout(2500);
await shot("w5-confirm", true);
await page.getByTestId("send-receipt").click();
await page.waitForTimeout(700);
const receiptUrl = (await page.getByTestId("receipt-url").textContent()).trim();
await shot("w6-qr", false);
await page.goto(base + "/app");
await page.getByTestId("registry-row").first().click();
await page.waitForTimeout(800);
await shot("fiche");
await page.getByTestId("verify-link").click();
await page.getByText(/Preuve intacte/).waitFor();
await page.waitForTimeout(600);
await shot("verify", false);
await page.getByTestId("simulate-fraud").click();
await page.waitForTimeout(800);
await shot("fraud", false);
await page.goto(base + "/app/litiges"); await page.waitForTimeout(500); await shot("litiges");
await page.goto(base + "/app/reglages"); await page.waitForTimeout(500); await shot("reglages");
await page.goto(receiptUrl); await page.waitForTimeout(1200); await shot("receipt");
await page.goto(base + "/comptoir"); await page.getByTestId("member-Camille").click(); await shot("comptoir", false);
await browser.close();
